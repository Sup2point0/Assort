<!--
	The layout for pages generated by Squarkdown.

	This should be kept in sync with `(hand)/`, the layout for special handwritten pages.

	The main differences are:

	- This has an `<article>` wrapper.
	- This adds a `<TagBlock>` at the end.
-->

<script lang="ts">

import { Nav, Footer } from "#parts/core";
import { Breadcrumbs, Header, TagsBlock } from "#parts/page";

import { page } from "$app/state";
import type { PageData } from "stranger-quarkdown";


let { children } = $props();

let data = $derived(page.data as PageData<"long">);

</script>


<div class="layout">
	<main>
		<Breadcrumbs page={data} />
		<Header />

		<article>
			{#if children != undefined}
				{@render children()}
			{:else}
				<p class="error">
					No page content!
				</p>
			{/if}
		</article>
	</main>

	<Nav />
</div>

{#if !page.data.tags?.includes("index")}
	<TagsBlock />
{/if}

<Footer />


<style lang="scss">
	
.layout {
	padding: 0 2rem;
	padding-top: 3rem;
	display: flex;
	flex-flow: row nowrap;

	main {
		flex: 1;
		margin-left: 2rem;
		margin-right: 4rem;
	}
}

</style>
